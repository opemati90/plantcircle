/** Same keys as English, any string values. */
type Shape<T> = { [K in keyof T]: T[K] extends string ? string : Shape<T[K]> };

/**
 * Languages with more plural forms than English may add them next to a `_one` key
 * (Polish has `_few` and `_many`). They are optional, so English stays the reference.
 */
type ExtraPluralForms<T> = {
  [
    K in keyof T as K extends `${infer Base}_one`
      ? `${Base}_zero` | `${Base}_two` | `${Base}_few` | `${Base}_many`
      : never
  ]?: string;
};
type LocaleShape<T> = {
  [K in keyof T]: T[K] extends string ? string : LocaleShape<T[K]>;
} & ExtraPluralForms<T>;

export type Catalog = LocaleShape<typeof en>;
